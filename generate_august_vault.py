def generate_vault(vault_dir: Path, year: int = 2026, month: int = 8):
    print(f"\n==================================================================")
    print(f"  Генерация хранилища: {vault_dir.resolve()}")
    print(f"  Временной диапазон: {year:04d}-{month:02d}-01 .. {year:04d}-{month:02d}-31")
    print(f"==================================================================")

    if vault_dir.exists():
        shutil.rmtree(vault_dir, ignore_errors=True)
    vault_dir.mkdir(parents=True, exist_ok=True)

    gs = GraphService()
    hs = HistoryService(graph_service=gs)

    stages = get_august_stages(year, month)

    for i, stage in enumerate(stages, 1):
        dt = datetime(year, month, stage["day"], stage["hour"], stage["minute"])
        ts = dt.timestamp()
        date_str = dt.strftime("%d.%m.%Y, %H:%M")

        # Запись файлов текущего дня
        for fname, content in stage["files"].items():
            fpath = vault_dir / fname
            fpath.write_text(content.strip() + "\n", encoding="utf-8")
            os.utime(fpath, (ts, ts))

        # Создание среза в SQLite
        snap = hs.create_snapshot(
            vault_dir,
            trigger=stage["trigger"],
            description=stage["desc"],
            force=True,
            custom_timestamp=ts,
            custom_created_at=date_str
        )

        print(f"[{i:02d}/{len(stages):02d}] {date_str} -> Снимок #{snap['id']}: {stage['desc']}")
        print(f"         Файлов: {snap['filesCount']} | Узлов графа: {snap['nodesCount']} | Связей: {snap['linksCount']}")

    # Финальная синхронизация графа
    gs.sync_graph_markdown_file(vault_dir)

    # Подсчет итогов
    md_files = [f for f in vault_dir.glob("*.md") if not f.name.startswith("_")]
    print(f"\n[УСПЕХ] Создано заметок: {len(md_files)} (всего файлов со служебными: {len(list(vault_dir.glob('*.md')))})")
    print(f"Снимков в истории: {len(stages)}")
    print(f"Каталог готов к открытию: {vault_dir.resolve()}\n")


