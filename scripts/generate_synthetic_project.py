        current_names = set(files_state.keys())
        # Физически удаляем с диска файлы, которые были удалены из files_state
        for on_disk in target_dir.glob("*.txt"):
            if on_disk.name not in current_names:
                try:
                    on_disk.unlink()
                except Exception:
                    pass

        # Записываем все актуальные файлы
        for fname, content in files_state.items():
            (target_dir / fname).write_text(content, encoding="utf-8")

