"""
generate_synthetic_project.py — Генератор реалистичного синтетического проекта сценариев
с непрерывной эволюцией всех файлов за 3 недели (21 день, 9 снапшотов).

Каждый файл претерпевает от 3 до 9 органичных редактур, моделируя реальную
работу над многосерийным детективным сценарием.

Строго соответствует канонической спецификации диалекта asleep (14 единиц):
- Заголовки '#' ликвидированы; '#' используется строго для тегов (#персонаж, #локация, #сюжет, #улика, #финал).
- Именованные однострочные и многострочные блоки: Имя { ... }
- Локальные трансклюзии: Имя()
- Межфайловые трансклюзии: Файл.Имя()
- Вики-ссылки: [[Название файла]]
- Форматирование: **жирный**, *курсив*, ~~зачеркнутый~~
- Списки: -, 1.
- Цитаты: >
- Разделители: --- (для оверлея линий)
- Удаление файлов: временные файлы 'Ложный след.txt' и 'Черновик допроса.txt'
  появляются на 10-й день, дополняются и удаляются по ходу расследования.
"""

import sys
import shutil
import time
from pathlib import Path
from datetime import datetime

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from services.history_service import HistoryService
from services.graph_service import GraphService
from services.storage.file_service import FileService
from services.storage.config_service import ConfigService


def build_synthetic_vault(target_dir: Path):
    target_dir.mkdir(parents=True, exist_ok=True)

    # 1. Очищаем старые файлы и БД истории
    for p in target_dir.glob("*.txt"):
        try:
            p.unlink()
        except Exception:
            pass
    for p in target_dir.glob("*.md"):
        try:
            p.unlink()
        except Exception:
            pass
    asleep_dir = target_dir / ".asleep"
    if asleep_dir.exists():
        try:
            shutil.rmtree(asleep_dir)
        except Exception:
            pass

