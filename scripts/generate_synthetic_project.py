    file_svc = FileService(cfg_svc)
    graph_svc = GraphService(None, file_svc, cfg_svc)
    history_svc = HistoryService(file_svc, graph_svc)

    print(f"[*] Генерация насыщенного синтетического проекта в: {target_dir}")

