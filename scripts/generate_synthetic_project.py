        d_str = datetime.fromtimestamp(timestamp_sec).strftime("%Y-%m-%d %H:%M:%S")
        history_svc.create_snapshot(
            target_dir,
            trigger=trigger,
            description=description,
            graph_data=g_data,
            force=True,
            custom_timestamp=timestamp_sec,
            custom_created_at=d_str
        )

